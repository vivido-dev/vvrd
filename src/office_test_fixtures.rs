pub fn create_embedded_image_docx(path: &Path) -> anyhow::Result<()> {
    let image = test_image_png()?;
    write_package(
        path,
        &[
            ("[Content_Types].xml", DOCX_CONTENT_TYPES.as_bytes()),
            ("_rels/.rels", DOCX_PACKAGE_RELS.as_bytes()),
            ("word/document.xml", DOCX_DOCUMENT.as_bytes()),
            (
                "word/_rels/document.xml.rels",
                DOCX_DOCUMENT_RELS.as_bytes(),
            ),
            ("word/media/image1.png", &image),
        ],
    )
}

